// Parse src/gen_*_families.h into api/sourceStats.ts (reference base stats and
// types). Run: npx tsx scripts/genSourceStats.ts
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'

const FIELDS: Record<string, string> = {
  baseHP: 'hp',
  baseAttack: 'attack',
  baseDefense: 'defense',
  baseSpeed: 'speed',
  baseSpAttack: 'specialAttack',
  baseSpDefense: 'specialDefense',
}

const out: Record<string, unknown> = {}
const files = readdirSync('src')
  .filter((f) => /^gen_\d+_families\.h$/.test(f))
  .sort()
for (const file of files) {
  const source = readFileSync(`src/${file}`, 'utf8')
  const parts = source.split(/^\s*\[SPECIES_([A-Z0-9_]+)\]\s*=/m)
  for (let i = 1; i < parts.length; i += 2) {
    const key = parts[i].toLowerCase().replace(/[^a-z0-9]/g, '')
    if (out[key]) continue
    const body = parts[i + 1]
    const stats: Record<string, number> = {}
    for (const [field, name] of Object.entries(FIELDS)) {
      const m = body.match(new RegExp(`\\.${field}\\s*=\\s*(\\d+)`))
      if (m) stats[name] = Number(m[1])
    }
    const t = body.match(/\.types\s*=\s*MON_TYPES\(\s*TYPE_(\w+)\s*(?:,\s*TYPE_(\w+))?/)
    if (!t || Object.keys(stats).length !== 6) continue
    const types = [t[1], t[2]]
      .filter((x): x is string => !!x)
      .map((x) => x.toLowerCase())
    out[key] = { stats, types: types[0] === types[1] ? [types[0]] : types }
  }
}

writeFileSync(
  'api/sourceStats.ts',
  `// Generated by scripts/genSourceStats.ts from src/gen_*_families.h. Do not edit.\nexport interface SourceSpecies {\n  stats: {\n    hp: number\n    attack: number\n    defense: number\n    specialAttack: number\n    specialDefense: number\n    speed: number\n  }\n  types: string[]\n}\n\nexport const SOURCE_SPECIES: Record<string, SourceSpecies> = ${JSON.stringify(out, null, 2)}\n`,
)
console.log(Object.keys(out).length, 'species')
